import assert from 'node:assert/strict';
import { isPlaythingsLocalArtifact, playthingsArtifactFindLabel, playthingsArtifactLocator, searchablePlaythingsArtifacts } from './playthings.find.js';
const localTask = { key: 'task', title: 'My Task', schemaId: 'tiinex.task.v1', sourceMode: 'local-transition-canonical', createdAt: '2026-09-03 10:00:00' };
const child = { key: 'child', title: 'Later Topic', schemaId: 'tiinex.topic.v1', sourceMode: 'package-import-workspace-file', createdAt: '2026-09-03 10:01:00' };
const actor = { id: 'lineage:task', headKey: 'child', label: 'Later Topic', ancestry: ['task','child'] };
const model = { artifacts: [localTask, child], actors: [actor] };
assert.equal(isPlaythingsLocalArtifact(localTask), true);
assert.equal(playthingsArtifactLocator(model, 'task').kind, 'lineage-history');
assert.equal(playthingsArtifactFindLabel(model, localTask), 'History → Later Topic');
assert.equal(searchablePlaythingsArtifacts(model, '', 5)[0].key, 'task', 'empty find query should surface user-local artifacts first');
assert.equal(searchablePlaythingsArtifacts(model, 'later', 5)[0].key, 'child');
console.log('✓ Playthings artifact finder resolves local/history representation');
